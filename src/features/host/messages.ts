const all: Record<Locale, HostMessages> = { ar, en };

export function hostMessages(locale: Locale): HostMessages {
  return all[locale];
}

// The sentence for a failed action, with its numbers filled in.
export function errorText(
  t: HostMessages,
  code: HostErrorCode,
  detail?: Record<string, string | number | string[]>,
): string {
  let text = t.errors[code] ?? t.errors.unknown;
  for (const [key, value] of Object.entries(detail ?? {})) {
    if (typeof value !== "object") text = text.replace(`{${key}}`, String(value));
  }
  if (code === "invalid" && typeof detail?.row === "number") text = `${text} ${t.errors.row.replace("{row}", String(detail.row))}`;
  return text;
}
